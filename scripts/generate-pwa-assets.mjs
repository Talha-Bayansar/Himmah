import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";
const source = "public/pwa/icon.svg";
for (const size of [32, 192, 512])
  await sharp(source)
    .flatten({ background: "#12382f" })
    .resize(size, size)
    .png()
    .toFile(`public/pwa/icon-${size}.png`);
await sharp(source)
  .flatten({ background: "#12382f" })
  .resize(180, 180)
  .png()
  .toFile("public/pwa/apple-touch-icon.png");
// Artwork lies within the central 80% maskable safe zone, with an opaque full bleed.
await sharp(source)
  .flatten({ background: "#12382f" })
  .resize(512, 512)
  .png()
  .toFile("public/pwa/icon-maskable-512.png");
const devices = [
  [320, 568, 2],
  [375, 667, 2],
  [414, 736, 3],
  [375, 812, 3],
  [390, 844, 3],
  [393, 852, 3],
  [402, 874, 3],
  [414, 896, 2],
  [414, 896, 3],
  [428, 926, 3],
  [430, 932, 3],
  [440, 956, 3],
  [420, 912, 3],
  [440, 960, 3],
  [744, 1133, 2],
  [768, 1024, 2],
  [810, 1080, 2],
  [820, 1180, 2],
  [834, 1112, 2],
  [834, 1194, 2],
  [1024, 1366, 2],
  [1032, 1376, 2],
];
const links = [];
for (const [width, height, ratio] of devices) {
  const mark = await sharp(source)
    .flatten({ background: "#12382f" })
    .resize(100 * ratio, 100 * ratio)
    .png()
    .toBuffer();
  for (const orientation of ["portrait", "landscape"]) {
    const w = (orientation === "portrait" ? width : height) * ratio;
    const h = (orientation === "portrait" ? height : width) * ratio;
    const href = `/pwa/splash-${width}-${height}-${ratio}-${orientation}.png`;
    await sharp({
      create: { width: w, height: h, channels: 3, background: "#12382f" },
    })
      .composite([{ input: mark, gravity: "centre" }])
      .png()
      .toFile(`public${href}`);
    links.push({
      href,
      media: `(device-width: ${width}px) and (device-height: ${height}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: ${orientation})`,
    });
  }
}
await writeFile(
  "src/pwa/splash-screens.ts",
  `// Generated by npm run pwa:assets.\nexport const splashScreens = ${JSON.stringify(links, null, 2)};\n`,
);
const offline = {};
for (const locale of ["en", "nl", "tr"]) {
  const messages = JSON.parse(
    await readFile(`messages/${locale}.json`, "utf8"),
  );
  const manifest = {
    id: "/",
    name: "Himmah Hub",
    short_name: "Himmah",
    description: messages.page_description,
    lang: locale,
    dir: "ltr",
    start_url: "/hub",
    scope: "/",
    display: "standalone",
    display_override: ["standalone"],
    background_color: "#12382f",
    theme_color: "#12382f",
    icons: [
      {
        src: "/pwa/icon-192.png",
        sizes: "192x192",
        type: "image/png",
        purpose: "any",
      },
      {
        src: "/pwa/icon-512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "any",
      },
      {
        src: "/pwa/icon-maskable-512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };
  await writeFile(
    `public/manifest.${locale}.webmanifest`,
    JSON.stringify(manifest, null, 2) + "\n",
  );
  offline[locale] = {
    title: messages.offline_title,
    description: messages.offline_description,
    retry: messages.try_again,
  };
}
await writeFile(
  "public/offline.html",
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="theme-color" content="#12382f"><title>Himmah</title><style>body{margin:0;min-height:100svh;display:grid;place-items:center;background:#f7f8f3;color:#153f36;font:16px/1.6 system-ui}main{max-width:420px;padding:32px}img{border-radius:24px}h1{font-size:30px;line-height:1.2}button{margin-top:16px;background:#153f36;color:white;border:0;border-radius:10px;padding:14px 24px;font:inherit;cursor:pointer}button:focus-visible{outline:3px solid #638344;outline-offset:3px}</style></head><body><main><img src="/pwa/icon-192.png" width="80" height="80" alt="Himmah"><h1 id="title">${offline.en.title}</h1><p id="description">${offline.en.description}</p><button id="retry">${offline.en.retry}</button></main><script>const messages=${JSON.stringify(offline)};const language=document.cookie.match(/(?:^|;\\s*)himmah_locale=(en|nl|tr)(?:;|$)/)?.[1]||"en";document.documentElement.lang=language;for(const id of ["title","description","retry"])document.getElementById(id).textContent=messages[language][id];document.getElementById("retry").onclick=()=>location.reload();</script></body></html>`,
);
